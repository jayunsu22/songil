// 가견적 ↔ 실제견적 품목별 비교 (quote_diff.js). 기대값: 목업 C 의 예 (샤시 3m→4m, 단창→2중창, 중문 신규, 싱크대 빠짐)
const test = require('node:test');
const assert = require('node:assert');
const D = require('../quote_diff.js');

const 가 = [
  { 체크_ID: 'a1', 구역: '거실', 품목명: '샤시1 (샤시(2중창))', 수량: 3, 단위: 'm', 표시금액: 331500 },
  { 체크_ID: 'a2', 구역: '거실', 품목명: '냉장고장옆 여닫이문', 수량: '', 단위: '', 표시금액: 220000 },
  { 체크_ID: 'b1', 구역: '방1', 품목명: '방1샤시 (샤시(단창))', 수량: 3, 단위: 'm', 표시금액: 201000 },
  { 체크_ID: 'k1', 구역: '주방', 품목명: '싱크대 하부장', 수량: 7, 단위: 'm', 표시금액: 343000 },
];
const 실 = [
  { 체크_ID: 'a1', 구역: '거실', 품목명: '샤시1 (샤시(2중창))', 수량: 4, 단위: 'm', 표시금액: 442000 },
  { 체크_ID: 'a2', 구역: '거실', 품목명: '냉장고장옆 여닫이문', 수량: '', 단위: '', 표시금액: 220000 },
  { 체크_ID: 'b1', 구역: '방1', 품목명: '방1샤시 (샤시(2중창))', 수량: 3, 단위: 'm', 표시금액: 331500 },
  { 체크_ID: 'h1', 구역: '현관', 품목명: '중문 양쪽', 수량: 1, 단위: '세트', 표시금액: 318500 },
];

test('변경·신규·빠짐, 금액이 같은 줄은 빠진다', () => {
  const r = D.비교(가, 실);
  assert.deepStrictEqual(r.바뀐.map((x) => [x.종류, x.이름, x.전, x.후, x.차이]), [
    ['변경', '샤시1', 331500, 442000, 110500],
    ['변경', '방1샤시', 201000, 331500, 130500],
    ['신규', '중문 양쪽', 0, 318500, 318500],
    ['빠짐', '싱크대 하부장', 343000, 0, -343000],
  ]);
  assert.ok(r.키별['id:a1'] && !r.키별['id:a2']);
});

test('이유: 길이·종류·수량·난이도, 모르면 금액 조정', () => {
  const r = D.비교(가, 실);
  assert.deepStrictEqual(r.바뀐[0].이유, ['길이 3m → 4m']);
  assert.deepStrictEqual(r.바뀐[1].이유, ['종류 단창 → 2중창']);
  assert.deepStrictEqual(D.이유({ 품목명: '방문', 수량: 1, 단위: '세트' }, { 품목명: '방문', 수량: 2, 단위: '세트' }), ['수량 1세트 → 2세트']);
  assert.deepStrictEqual(D.이유({ 품목명: '방문', 난이도: 1 }, { 품목명: '방문', 난이도: 1.2 }), ['난이도 1 → 1.2']);
  assert.deepStrictEqual(D.이유({ 품목명: '방문' }, { 품목명: '방문' }), ['금액 조정']);
  assert.deepStrictEqual(D.이유({ 품목명: '시스템샤시 (시스템샤시)' }, { 품목명: '시스템샤시 (샤시(단창))' }), ['종류 시스템 → 단창']);
});

test('금액 함수를 받는다 (인건비 견적서)', () => {
  const r = D.비교([{ 체크_ID: 'x', 품목명: 'a', 표시금액: 10, 인건비표시금액: 5 }], [{ 체크_ID: 'x', 품목명: 'a', 표시금액: 10, 인건비표시금액: 7 }], (l) => l.인건비표시금액);
  assert.strictEqual(r.바뀐[0].차이, 2);
});

test('체크_ID 없는 예전 줄은 구역+이름으로 짝짓는다', () => {
  const r = D.비교([{ 구역: '거실', 품목명: '아트월', 표시금액: 100 }], [{ 구역: '거실', 품목명: '아트월', 표시금액: 100 }]);
  assert.strictEqual(r.바뀐.length, 0);
});
