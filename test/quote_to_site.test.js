test('견적사진만: 견적에 넣은 품목에 붙은 사진만', () => {
  const 상태 = {
    선택: { 'z05_방1_방문_공통': {} },
    직접품목: [{ id: 'c1', 구역: '주방', 품목명: '식탁상판' }],
  };
  const 사진들 = [
    { id: 1, 태그: ['z05_방1_방문_공통'] },                       // 넣은 품목 → 보냄
    { id: 2, 태그: ['z05_방1_샤시1_공통'] },                      // 찍기만 하고 견적엔 안 넣음 → 안 보냄
    { id: 3, 태그: [] },                                          // 어느 품목에도 안 붙음 → 안 보냄
    { id: 4, 태그: [], 표시: { 'z05_방1_방문_공통': [[0, 0, 1, 1]] } }, // 네모만 남은 넣은 품목 → 보냄
    { id: 5, 태그: [], 표시: { 'z05_방1_방문_공통': [] } },        // 빈 네모 → 안 보냄
    { id: 6, 태그: ['c1'] },                                      // 직접품목 → 보냄
    { id: 7, 태그: ['z05_방1_샤시1_공통', 'z05_방1_방문_공통'] },  // 하나라도 넣은 품목 → 보냄
    { id: 8 },                                                    // 태그 없음 → 안 보냄
  ];
  assert.deepStrictEqual(견적사진만(사진들, 상태).map((p) => p.id), [1, 4, 6, 7]);
});

test('견적사진만: 빈 입력도 안전', () => {
  assert.deepStrictEqual(견적사진만(null, null), []);
  assert.deepStrictEqual(견적사진만([{ id: 1, 태그: ['x'] }], {}), []);
});

