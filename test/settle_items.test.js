// 정산견적 [품목 견적] 계산. 기대값 출처: 에어테이블 '시공품목정보' 표 숫자로 손 계산 (request_price.test.js 와 같은 표)
//   방문 6.5m × (25,000 + 9,000) = 221,000 (인건비 162,500)
//   문틀 2m × (47,000 + 9,000) = 112,000 (사장님 확인, 인건비 94,000)
//   한쪽면 = 필름 절반 3.3m(6.5/2 → 소수 1자리 3.3) × 34,000 = 112,200
const test = require('node:test');
const assert = require('node:assert');
const I = require('../settle_items.js');
const 표 = require('./fixtures/price_table_sample.json');

const 줄 = (품목명, 덧) => Object.assign({ key: 'k', 품목명, 출처: '작업목록', 체크: true }, 덧 || {});

test('줄금액: 방문 기본 221,000 (인건비 162,500 · 자재비 58,500)', () => {
  const r = I.줄금액(줄('방2문+틀'), 표, {}, 9000);
  assert.deepStrictEqual([r.금액, r.인건비, r.자재비, r.필름m, r.문제, r.고침], [221000, 162500, 58500, 6.5, null, false]);
});

test('줄금액: 시공범위 문틀만 → 문틀 112,000, 한쪽면 → 절반 m', () => {
  assert.strictEqual(I.줄금액(줄('방2문+틀', { 시공범위: '문틀만 시공' }), 표, {}, 9000).금액, 112000);
  const h = I.줄금액(줄('방2문+틀', { 시공범위: '문+틀 한쪽면 시공' }), 표, {}, 9000);
  assert.strictEqual(h.필름m, 3.3);
  assert.strictEqual(h.금액, 112200);
});

test('줄금액: 개수·난이도·필름 단가', () => {
  assert.strictEqual(I.줄금액(줄('방2문+틀', { 품목: { 개수: 2 } }), 표, {}, 9000).금액, 442000);
  assert.strictEqual(I.줄금액(줄('방2문+틀', { 품목: { 난이도: 1.2 } }), 표, {}, 9000).금액, Math.round(221000 * 1.2));
  assert.strictEqual(I.줄금액(줄('방2문+틀'), 표, {}, 12000).금액, Math.round(6.5 * 37000));
});

test('줄금액: 사장님이 고친 금액이 먼저 (자재비 = 합계 − 인건비)', () => {
  const r = I.줄금액(줄('방2문+틀', { 품목: { 고침: { 금액: 200000, 인건비: 150000 } } }), 표, {}, 9000);
  assert.deepStrictEqual([r.금액, r.인건비, r.자재비, r.고침, r.자동.금액], [200000, 150000, 50000, true, 221000]);
});

test('줄금액: 단가표에 없는 품목은 0원이 아니라 문제 표시, 고치면 그 금액', () => {
  const r = I.줄금액(줄('방1파티션'), 표, {}, 9000);
  assert.strictEqual(r.문제, '단가없음');
  assert.strictEqual(r.금액, 0);
  const f = I.줄금액(줄('방1파티션', { 품목: { 고침: { 금액: 150000, 인건비: 150000 } } }), 표, {}, 9000);
  assert.deepStrictEqual([f.문제, f.금액], [null, 150000]);
});

test('줄금액: 문선만은 m 를 골라야 한다', () => {
  assert.strictEqual(I.줄금액(줄('방2문+틀', { 시공범위: '문선만 시공' }), 표, {}, 9000).문제, 'm없음');
  assert.strictEqual(I.줄금액(줄('방2문+틀', { 시공범위: '문선만 시공', 품목: { m: 2 } }), 표, {}, 9000).금액, 68000);
});

test('합계: 체크한 작업목록 줄만, 문제 있는 줄은 빼고 이름을 돌려준다', () => {
  const 줄들 = [
    줄('방2문+틀'),
    줄('방2문+틀', { key: 'k2', 시공범위: '문틀만 시공' }),
    줄('거실화장실문', { 체크: false }),
    줄('방1파티션'),
    { 품목명: '실리콘', 출처: '추가', 종류: '금액', 금액: 50000, 체크: true },   // 직접 추가 줄은 여기서 안 센다
  ];
  const h = I.합계(줄들, 표, {}, () => 9000);
  assert.deepStrictEqual([h.금액, h.인건비, h.자재비], [333000, 256500, 76500]);
  assert.deepStrictEqual(h.문제줄, ['방1파티션']);
});

test('줄금액: 현관문은 한쪽면을 골라도 170,000 (표 금액이 안쪽면만 기준)', () => {
  assert.strictEqual(I.줄금액(줄('현관문', { 시공범위: '문+틀 한쪽면 시공' }), 표, {}, 9000).금액, 170000);
});
