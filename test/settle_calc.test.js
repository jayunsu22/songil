const test = require('node:test');
const assert = require('node:assert');
const { 줄소모량, 자재별소계, 자재없음줄, 인건비, 합계 } = require('../settle_calc.js');

/* 정산견적 계산. 기대값은 스펙(docs/superpowers/specs/2026-09-20-settle-quote-design.md §3)의
   규칙을 손으로 계산한 것이다:
   - 줄 소모량 = 직접소모량 ?? (길이입력 ? 마스터소모량×길이 : 마스터소모량×수량), 소수 1자리
   - 자재별 금액 = round(소모량합 × 단가), 소모량합은 소수 1자리로 맞춘 뒤 곱한다
   - 총액 = 인건비 + Σ자재 + Σ부가 */

const 자재표 = {
  A: { 항목명: 'LX 프리미엄', 단가: 12000 },
  B: { 항목명: '영림 기본', 단가: 8000 },
};
const 줄 = (o) => Object.assign({ 품목명: '품목', 구역: '방1', 체크: true, 길이입력: false,
  마스터소모량: 0, 수량: 1, 길이: null, 직접소모량: null, 자재ID: 'A' }, o);

test('세트 품목: 마스터 6.5 × 수량 2 → 13.0', () => {
  assert.strictEqual(줄소모량(줄({ 마스터소모량: 6.5, 수량: 2 })), 13);
});

test('길이 품목: 마스터 1 × 길이 3.2 → 3.2, 길이 없으면 0', () => {
  assert.strictEqual(줄소모량(줄({ 길이입력: true, 마스터소모량: 1, 길이: 3.2 })), 3.2);
  assert.strictEqual(줄소모량(줄({ 길이입력: true, 마스터소모량: 1, 길이: null })), 0);
  assert.strictEqual(줄소모량(줄({ 길이입력: true, 마스터소모량: 1, 길이: '' })), 0);
});

test('몰딩: 0.1 × 12.3m → 1.2 (소수 1자리 반올림)', () => {
  assert.strictEqual(줄소모량(줄({ 길이입력: true, 마스터소모량: 0.1, 길이: 12.3 })), 1.2);
});

test('직접소모량이 있으면 마스터 계산을 덮는다', () => {
  assert.strictEqual(줄소모량(줄({ 마스터소모량: 6.5, 수량: 3, 직접소모량: 5 })), 5);
  // 0 도 '직접 입력한 값'이다 - null 과 구분한다
  assert.strictEqual(줄소모량(줄({ 마스터소모량: 6.5, 직접소모량: 0 })), 0);
});

test('체크 해제 줄은 소계에서 빠진다', () => {
  const 소계 = 자재별소계([
    줄({ 마스터소모량: 6.5 }),
    줄({ 마스터소모량: 6.5, 체크: false }),
  ], 자재표);
  assert.deepStrictEqual(소계, [{ 자재ID: 'A', 자재명: 'LX 프리미엄', 단가: 12000, 소모량합: 6.5, 금액: 78000 }]);
});

test('자재 2종 묶음: A 6.5+3.2 = 9.7m → 116,400 / B 2.0m → 16,000', () => {
  const 소계 = 자재별소계([
    줄({ 마스터소모량: 6.5 }),
    줄({ 길이입력: true, 마스터소모량: 1, 길이: 3.2 }),
    줄({ 마스터소모량: 2, 자재ID: 'B' }),
  ], 자재표);
  assert.deepStrictEqual(소계, [
    { 자재ID: 'A', 자재명: 'LX 프리미엄', 단가: 12000, 소모량합: 9.7, 금액: 116400 },
    { 자재ID: 'B', 자재명: '영림 기본', 단가: 8000, 소모량합: 2, 금액: 16000 },
  ]);
});

test('금액 반올림: 0.1×3 = 0.3m × 9000 = 2,700 (부동소수점 오차 방지)', () => {
  const 소계 = 자재별소계([
    줄({ 길이입력: true, 마스터소모량: 0.1, 길이: 1 }),
    줄({ 길이입력: true, 마스터소모량: 0.1, 길이: 1 }),
    줄({ 길이입력: true, 마스터소모량: 0.1, 길이: 1 }),
  ], { A: { 항목명: '기본', 단가: 9000 } });
  assert.strictEqual(소계[0].소모량합, 0.3);
  assert.strictEqual(소계[0].금액, 2700);
});

test('자재표에 없는 자재ID → 소계 제외 + 자재없음줄에 잡힘', () => {
  const 줄들 = [줄({ 마스터소모량: 6.5 }), 줄({ 마스터소모량: 6.5, 자재ID: 'ZZZ' }), 줄({ 마스터소모량: 1, 자재ID: 'ZZZ', 체크: false })];
  const 소계 = 자재별소계(줄들, 자재표);
  assert.strictEqual(소계.length, 1);
  assert.strictEqual(소계[0].소모량합, 6.5);
  assert.strictEqual(자재없음줄(줄들, 자재표).length, 1);   // 체크 해제된 건 경고 대상 아님
});

test('합계: 품수 8 × 250,000 + 자재 132,400 + 부가(식대 40,000, 0원 줄 무시) = 2,172,400', () => {
  const r = 합계({
    품수: 8, 품단가: 250000,
    줄들: [줄({ 마스터소모량: 6.5 }), 줄({ 길이입력: true, 마스터소모량: 1, 길이: 3.2 }), 줄({ 마스터소모량: 2, 자재ID: 'B' })],
    부가: [{ 항목명: '식대', 금액: 40000 }, { 항목명: '퀵비', 금액: 0 }, { 항목명: '부자재비', 금액: '' }],
  }, 자재표);
  assert.strictEqual(r.인건비, 2000000);
  assert.strictEqual(r.자재비, 132400);
  assert.strictEqual(r.부가, 40000);
  assert.strictEqual(r.총액, 2172400);
  assert.strictEqual(r.자재소계.length, 2);
});

test('합계: 품수 0.5 도 허용, 빈 값은 0', () => {
  assert.strictEqual(합계({ 품수: 0.5, 품단가: 200000, 줄들: [], 부가: [] }, 자재표).인건비, 100000);
  assert.strictEqual(합계({ 품수: '', 품단가: 200000, 줄들: [], 부가: [] }, 자재표).총액, 0);
});

test('인건비 반품 반올림: 8.5품 × 250,000 = 2,000,000 + (12.5만→13만) = 2,130,000', () => {
  assert.strictEqual(인건비(8.5, 250000), 2130000);
});

test('인건비 반품 반올림: 1.5품 × 270,000 = 270,000 + (13.5만→14만) = 410,000', () => {
  assert.strictEqual(인건비(1.5, 270000), 410000);
  assert.strictEqual(인건비(0.5, 260000), 130000);   // 정확히 나뉘면 그대로
  assert.strictEqual(인건비(2.5, 230000), 460000 + 120000);   // 11.5만 → 12만
});

test('인건비 정수 품수는 반올림 없음, 합계에도 같은 규칙', () => {
  assert.strictEqual(인건비(2, 250000), 500000);
  assert.strictEqual(합계({ 품수: 8.5, 품단가: 250000, 줄들: [], 부가: [] }, 자재표).총액, 2130000);
});
