/* ---------- 평형 전체 샤시 (사장님 2026-11-02) ----------
   20평 = 거실·주방·방1·방2 + 각 베란다 (8틀), 30평 + 방3, 40평 + 방4, 50평 + 방5. 자리마다 3m */
const 샤시자리 = (구역, 이름) => 품('s_' + 구역 + '_' + 이름, 이름, 샤시옵션, 'm');
const 집 = [
  { 구역: '거실', items: [샤시자리('거실', '샤시1'), 샤시자리('거실', '샤시2'), 샤시자리('거실', '베란다샤시1')] },
  { 구역: '주방', items: [샤시자리('주방', '샤시1'), 샤시자리('주방', '베란다샤시1')] },
  { 구역: '현관', items: [샤시자리('현관', '샤시1')] },
].concat([1, 2, 3, 4, 5].flatMap((n) => [
  { 구역: '방' + n, items: [샤시자리('방' + n, '샤시1'), 샤시자리('방' + n, '샤시2')] },
  { 구역: '방' + n + '베란다', items: [샤시자리('방' + n + '베란다', '샤시1')] },
]));

test('평형 전체 샤시: 김성현님 문의 (32평 → 30평) → 거실·주방·방1~3 과 각 베란다 10틀, 3m 씩', () => {
  // 지금 n8n 이 1세트로 덮어써도 (근거에 '전체', 공통.평형 '30평') 방마다 담는다
  const 줄 = { 품목명: '샤시(단창)', 수량: 3, 표시수량: '1세트', 구역: '', 근거: '전체샷시필름 견적이 어느정도 나올까요?' };
  const r = D.체크하기([줄], 집, {}, { 평형: '30평' });
  assert.deepStrictEqual(Object.keys(r.선택), [
    's_거실_샤시1', 's_거실_베란다샤시1', 's_주방_샤시1', 's_주방_베란다샤시1', 's_방1_샤시1', 's_방1베란다_샤시1',
    's_방2_샤시1', 's_방2베란다_샤시1', 's_방3_샤시1', 's_방3베란다_샤시1']);
  Object.values(r.선택).forEach((x) => assert.deepStrictEqual(x, { 수량: 3, 난이도: 1, 옵션: 0, 초안: true }));
  assert.deepStrictEqual(r.평형샤시, [{ 품목명: '샤시(단창)', 평형: '30평', 틀: 10 }]);
  assert.deepStrictEqual(r.확인필요, []);
  // AI 가 10세트(30m) 로 읽어도 같다
  assert.deepStrictEqual(Object.keys(D.체크하기([Object.assign({}, 줄, { 수량: 30, 표시수량: '10세트' })], 집, {}, { 평형: '30평' }).선택).length, 10);
});

