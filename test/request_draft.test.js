test('평형 전체 샤시가 아닌 것은 예전처럼: 개수를 말했거나, 평형을 모르거나, 구역을 말했거나', () => {
  const 줄 = (근거, 표시수량, 수량, 구역) => ({ 품목명: '샤시(단창)', 수량, 표시수량, 구역: 구역 || '', 근거 });
  // '전체 샤시 3틀' → 3자리 (거실 샤시1·샤시2·베란다샤시1)
  assert.strictEqual(Object.keys(D.체크하기([줄('전체 샤시 3틀', '3세트', 9)], 집, {}, { 평형: '30평' }).선택).length, 3);
  // 평형을 모르면 한 자리 (예전 그대로)
  assert.strictEqual(Object.keys(D.체크하기([줄('전체 샤시', '1세트', 3)], 집, {}, {}).선택).length, 1);
  // '전체' 가 없으면 예전 그대로
  assert.strictEqual(Object.keys(D.체크하기([줄('샤시 견적', '1세트', 3)], 집, {}, { 평형: '30평' }).선택).length, 1);
  // 구역을 말했으면 그 구역
  assert.deepStrictEqual(Object.keys(D.체크하기([줄('거실 전체 샤시', '1세트', 3, '거실')], 집, {}, { 평형: '30평' }).선택), ['s_거실_샤시1']);
});

