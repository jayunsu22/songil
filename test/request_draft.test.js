// 견적초안 ①② (request_draft.js): 1분견적이 읽은 품목 → 방문견적 체크. 기준: 사장님 2026-10-29
//   세트 = 문짝+문틀, 화장실문 2개 = 거실·방1, 1분견적 규칙(샤시 1개 3m)
const test = require('node:test');
const assert = require('node:assert');
const D = require('../request_draft.js');

const 품 = (id, 이름, 옵션들, 단위) => ({ 체크_ID: id, 표시_품목명: 이름, 기본수량: 1, 단위: 단위 || '개', 적용평형: '공통', 옵션들: 옵션들.map((n) => ({ 품목명: n, 단위: 단위 || '개' })) });
const 샤시옵션 = ['샤시(단창)', '샤시(2중창)', '시스템샤시'];
const zones = [
  { 구역: '전체공통', items: [품('z00_전체_방문', '방문', ['방문'])] },
  { 구역: '방1', items: [품('z05_방1_방문', '방문', ['방문']), 품('z05_방1_화장실문', '화장실문', ['화장실문'])] },
  { 구역: '거실', items: [품('z01_거실_화장실문', '화장실문', ['화장실문']), 품('z01_거실_샤시1', '샤시1', 샤시옵션, 'm'), 품('z01_거실_샤시2', '샤시2', 샤시옵션, 'm')] },
  { 구역: '주방', items: [품('z02_주방_싱크대', '싱크대', ['싱크대'], 'm')] },
  { 구역: '방2', items: [품('z06_방2_방문', '방문', ['방문'])] },
  { 구역: '방3', items: [품('z07_방3_방문', '방문', ['방문'])] },
];
const 줄 = (품목명, 수량, 표시수량, 구역) => ({ 품목명, 수량, 표시수량, 구역: 구역 || '', 근거: 품목명 });

test('구역 순서: 거실·주방·현관·방1~5 먼저, 전체공통은 빼고, 나머지는 MASTER 순서', () => {
  assert.deepStrictEqual(D.구역순서(zones), ['거실', '주방', '방1', '방2', '방3']);
});

test('시험 1: 방문3세트·화장실문2세트 → 방1·방2·방3 방문, 거실·방1 화장실문', () => {
  const r = D.체크하기([줄('방문', 3, '3개'), 줄('화장실문', 2, '2개')], zones, {});
  assert.deepStrictEqual(Object.keys(r.선택).sort(), ['z01_거실_화장실문', 'z05_방1_방문', 'z05_방1_화장실문', 'z06_방2_방문', 'z07_방3_방문']);
  Object.values(r.선택).forEach((s) => assert.deepStrictEqual(s, { 수량: 1, 난이도: 1, 옵션: 0, 초안: true }));
  assert.deepStrictEqual([r.건너뜀, r.확인필요], [[], []]);
});

test('샤시 2세트(6m) → 거실 샤시1·샤시2 에 3m 씩, 단창 옵션', () => {
  const r = D.체크하기([줄('샤시(단창)', 6, '2세트')], zones, {});
  assert.deepStrictEqual(r.선택, {
    z01_거실_샤시1: { 수량: 3, 난이도: 1, 옵션: 0, 초안: true },
    z01_거실_샤시2: { 수량: 3, 난이도: 1, 옵션: 0, 초안: true },
  });
});

test('샤시(2중창) 5m → 한 자리에 5m, 2중창 옵션 순번', () => {
  const r = D.체크하기([줄('샤시(2중창)', 5, '5m')], zones, {});
  assert.deepStrictEqual(r.선택, { z01_거실_샤시1: { 수량: 5, 난이도: 1, 옵션: 1, 초안: true } });
});

test('싱크대 5.5m → 주방 싱크대 5.5', () => {
  const r = D.체크하기([줄('싱크대', 5.5, '5.5m')], zones, {});
  assert.deepStrictEqual(r.선택, { z02_주방_싱크대: { 수량: 5.5, 난이도: 1, 옵션: 0, 초안: true } });
});

test('구역을 말했으면 그 구역만', () => {
  const r = D.체크하기([줄('방문', 1, '1개', '방2')], zones, {});
  assert.deepStrictEqual(Object.keys(r.선택), ['z06_방2_방문']);
});

test('자리가 모자라면 남은 개수는 확인 필요', () => {
  const r = D.체크하기([줄('방문', 4, '4개')], zones, {});
  assert.strictEqual(Object.keys(r.선택).length, 3);
  assert.deepStrictEqual(r.확인필요, [{ 품목명: '방문', 개수: 1, 근거: '방문', 이유: '담을 자리가 모자람' }]);
});

test('방문견적에 없는 품목은 확인 필요 (버리지 않는다)', () => {
  const r = D.체크하기([줄('쇼파', 1, '1개')], zones, {});
  assert.deepStrictEqual(r.선택, {});
  assert.deepStrictEqual(r.확인필요, [{ 품목명: '쇼파', 개수: 1, 근거: '쇼파', 이유: '방문견적에 없는 품목' }]);
});

test('이미 체크된 자리는 건드리지 않고 건너뜀 — 두 번 눌러도 두 배가 안 된다', () => {
  const 이미 = { z05_방1_방문: { 수량: 1, 난이도: 1, 옵션: 0 } };
  const r = D.체크하기([줄('방문', 3, '3개')], zones, 이미);
  assert.deepStrictEqual(Object.keys(r.선택), ['z06_방2_방문', 'z07_방3_방문']);
  assert.deepStrictEqual(r.건너뜀, [{ 품목명: '방문', 구역: '방1', 체크_ID: 'z05_방1_방문' }]);
  assert.deepStrictEqual(r.확인필요, []);
});

test('품목명은 띄어쓰기를 무시하고 맞춘다', () => {
  const r = D.체크하기([줄('화장실 문', 1, '1개')], zones, {});
  assert.deepStrictEqual(Object.keys(r.선택), ['z01_거실_화장실문']);
});

test('빠진것: 사는 집인지·위치·다른 공정·필름·날짜 중 빈 것', () => {
  assert.deepStrictEqual(D.빠진것({ 거주: '살고 있음', 위치: '', 다른공정: '', 필름: 'PS010', 날짜: '' }), ['위치', '다른 공정', '날짜']);
  assert.deepStrictEqual(D.빠진것(null), ['사는 집인지', '위치', '다른 공정', '필름', '날짜']);
});
