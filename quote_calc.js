// 견적 금액 계산. DOM/네트워크에 손대지 않는 순수 모듈.
// 브라우저(<script src>)와 node(require) 양쪽에서 로드된다.
//
// 이 파일이 이 도구에서 유일하게 "틀리면 안 되는" 부분이라 DOM에서 떼어내
// test/quote_calc.test.js 로 검증한다.
(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.QuoteCalc = factory();
})(typeof self !== 'undefined' ? self : this, function () {

  // 시공품목정보의 [예상_총금액] 수식과 같은 계산이다.
  //   IF(평형별_설정길이 > 0, 평형별_설정길이 * 자재소모량, 자재소모량)
  //     * (자재비단가 + 인건비단가) * 난이도계수
  //
  // 자재소모량은 (인건비+자재비) 전체에 곱한다. 자재비에만 곱하는 게 아니다.
  // 평형별 품목은 화면에서 수량 = 평형별_설정길이 로 넣으므로 같은 결과가 된다.
  function lineAmount(item) {
    // 직접 입력한 품목(방화문 양면·쌍여닫이처럼 기준 단가로 안 잡히는 건)은
    // 계산하지 않고 적어 넣은 금액을 그대로 쓴다. 최종 금액을 적는 칸이라
    // 여기에 난이도나 수량을 또 곱하면 적은 숫자와 달라진다.
    // != null 로 봐야 한다. 0 을 falsy 로 보고 넘기면 엉뚱한 금액이 나온다.
    if (item.직접금액 != null) return Math.round(item.직접금액);
    const 단가 = ((item.인건비단가 || 0) + (item.자재비단가 || 0)) * (item.자재소모량 || 0);
    return Math.round(단가 * (item.난이도 || 1) * (item.수량 || 0));
  }

  /* 인건비 몫.
     "자재는 내가 댈 테니 인건비만 계산해 달라" 는 업자가 있다. 그때 자재비를
     빼고 인건비만으로 견적을 내보내기 위한 값이다.

     자재소모량은 인건비에도 곱한다 - 합산 금액을 낼 때와 같은 규칙이어야
     인건비 몫 + 자재비 몫 = 라인금액 이 된다.

     직접 입력 품목은 적어 넣은 인건비를 그대로 쓴다. 인건비/자재비를 나눠
     적기 전에 넣은 예전 항목은 나눌 방법이 없으므로 null 을 돌려준다 -
     0 으로 돌려주면 인건비가 0원인 것처럼 보여서 금액이 틀린다. */
  function lineWage(item) {
    if (item.직접금액 != null) {
      return item.인건비 != null ? Math.round(item.인건비) : null;
    }
    const 단가 = (item.인건비단가 || 0) * (item.자재소모량 || 0);
    return Math.round(단가 * (item.난이도 || 1) * (item.수량 || 0));
  }

  /* 금액 칸 표시/읽기. '250,000원' 처럼 보여준다.
     type=number 는 콤마와 '원' 을 못 받아서 글자 칸으로 두고 직접 맞춘다.

     빈 칸을 '0원' 으로 만들면 안 된다 - 지우고 다시 쓸 수가 없어진다.
     마이너스만 친 상태도 지우면 빼는 항목을 입력할 수 없다. */
  function 금액포맷(글) {
    const 원본 = String(글 == null ? '' : 글);
    const 음수 = /^\s*-/.test(원본);
    const 숫자 = 원본.replace(/[^0-9]/g, '');
    if (!숫자) return 음수 ? '-' : '';
    return (음수 ? '-' : '') + Number(숫자).toLocaleString('ko-KR') + '원';
  }

  // 안 적은 것(NaN)과 0원을 구분해야 하므로 빈 칸은 NaN 을 돌려준다.
  function 금액파싱(글) {
    const 원본 = String(글 == null ? '' : 글);
    const 숫자 = 원본.replace(/[^0-9]/g, '');
    if (!숫자) return NaN;
    return (/^\s*-/.test(원본) ? -1 : 1) * Number(숫자);
  }

  /* 견적서 합계 절삭 (2026-10-20). 합계는 만원 단위 아래를 버린다 - 3,111,000원 → 3,110,000원.
     품목 금액은 그대로 두고 합계에서만 버린다. 버린 금액은 견적서에 '절삭' 줄로 보여줘서
     품목을 더한 값과 합계가 왜 다른지 받는 쪽이 알 수 있게 한다.
     마이너스(빼는 금액이 더 큰 경우)는 0 쪽으로 버린다 - 절삭으로 금액이 커지면 안 된다. */
  const 절삭단위 = 10000;
  function 절삭(금액) {
    const n = Math.round(Number(금액) || 0);
    return n >= 0 ? Math.floor(n / 절삭단위) * 절삭단위 : -Math.floor(-n / 절삭단위) * 절삭단위;
  }

  /* 금액 고치기 (2026-11-01). 현장에서 말로 알려준 금액에 맞춰 품목 금액을 고치면
     인건비·자재비를 원래 비율대로 나눈다 - 170,000(인건비 125,000) 을 150,000 으로 → 인건비 110,294.
     인건비를 반올림하고 자재비는 나머지로 둔다 - 둘을 따로 반올림하면 합이 고친 금액과 1원 어긋난다.
     원래 금액이 0 이면 나눌 비율이 없어 전부 인건비로 본다.
     원래 인건비를 모르는 줄(인건비/자재비를 나눠 적기 전 직접 입력)은 나누지 않고 null 로 둔다 -
     0 으로 두면 '인건비만 보내기' 에서 인건비가 0원인 것처럼 보인다. */
  function 금액나누기(새금액, 원래인건비, 원래금액) {
    const 금액 = Math.round(Number(새금액) || 0);
    if (원래인건비 == null) return { 금액: 금액, 인건비: null, 자재비: null };
    const 합 = Number(원래금액) || 0;
    const 인건비 = 합 ? Math.round(금액 * Number(원래인건비) / 합) : 금액;
    return { 금액: 금액, 인건비: 인건비, 자재비: 금액 - 인건비 };
  }

  /* 전체 조정은 총액에서 한 번에 (2026-11-02 사장님). 품목마다 나눠 걸지 않는다 - 품목 금액은 단가 그대로 두고,
     견적서 합계 위에 '조정 (업자단가 -5%) -60,450원' · '조정 (할인) -100,000원' 줄로 빼거나 더한다.
       % 조정  : 조정금액 = 기준(소계) × 비율 (원 단위 반올림)
       금액 조정: '직접입력' 으로 적은 금액 그대로 (-100,000원)
     % 끼리는 곱이 아니라 합이다 - 거주중 +10% 와 업자단가 -10% 는 상쇄되어야 하고 암산으로 검산할 수 있어야 한다.
     발행한 조정_내역에는 방식: '총액' 을 붙인다. 그 전에 발행한 견적서는 조정이 품목 금액에 이미 들어 있어서
     (방식 없음) 견적서 화면이 예전처럼 보여준다. */
  function 금액조정(a) { return !!a && typeof a.금액 === 'number' && isFinite(a.금액); }
  function 조정계산(기준, 조정내역) {
    const 줄들 = (조정내역 || []).filter(Boolean).map(function (a) {
      const 조정금액 = 금액조정(a) ? Math.round(a.금액) : Math.round((Number(기준) || 0) * (Number(a.비율) || 0));
      return Object.assign({}, a, { 방식: '총액', 조정금액: 조정금액 });
    });
    return { 줄들: 줄들, 합: 줄들.reduce(function (s, a) { return s + a.조정금액; }, 0) };
  }
  // 총액에서 거는 조정인 견적서인가 (발행한 조정_내역으로 안다)
  function 총액조정(조정내역) {
    return Array.isArray(조정내역) && 조정내역.some(function (a) { return a && a.방식 === '총액'; });
  }

  function calcQuote(items, adjustments) {
    // 품목 금액은 단가 그대로 (조정을 나눠 걸지 않는다). 표시금액 = 라인금액
    const 라인들 = (items || []).map(function (it) {
      const 라인금액 = lineAmount(it);
      const 인건비금액 = lineWage(it);
      return Object.assign({}, it, {
        라인금액: 라인금액,
        표시금액: 라인금액,
        // 인건비만 보내는 견적서에서 쓴다. 나눌 수 없는 줄은 null 이다.
        인건비금액: 인건비금액,
        인건비표시금액: 인건비금액,
      });
    });
    const 소계 = 라인들.reduce(function (s, l) { return s + l.라인금액; }, 0);
    const 조정 = 조정계산(소계, adjustments);
    // 총액 = 소계 + 조정. 그 합에서 만원 아래만 버린다(절삭)
    const 합 = 소계 + 조정.합;
    // 인건비만 보낼 때의 총액. 나눌 수 없는 줄(예전에 넣은 직접 입력 품목)은
    // 자재비가 섞인 채로 전액이 들어간다 - 모르는 값을 0 으로 깎으면
    // 사장님이 받을 돈이 줄어든다. 화면에는 그 줄에 '자재 포함' 을 붙인다.
    // 조정은 인건비 합계에 다시 건다 (% 는 인건비 합계의 %, 금액은 그대로)
    const 인건비소계 = 라인들.reduce(function (s, l) {
      return s + (l.인건비표시금액 == null ? l.표시금액 : l.인건비표시금액);
    }, 0);
    const 인건비조정 = 조정계산(인건비소계, adjustments);
    const 인건비합 = 인건비소계 + 인건비조정.합;
    return {
      소계: 소계,
      // 품목 금액에 건 비율 - 이제 늘 0 (조정은 총액에서). 발행 데이터의 같은 이름 칸에 그대로 실린다
      조정_합계율: 0,
      조정율합: 조정.줄들.reduce(function (s, a) { return s + (금액조정(a) ? 0 : (Number(a.비율) || 0)); }, 0),
      조정들: 조정.줄들,   // 발행할 때 조정_내역으로 싣는다 (방식: '총액', 조정금액)
      조정액: 조정.합,
      인건비조정들: 인건비조정.줄들,
      인건비조정액: 인건비조정.합,
      라인들: 라인들,
      절삭전총액: 합,
      총액: 절삭(합),
      절삭액: 합 - 절삭(합),
      인건비절삭전총액: 인건비합,
      인건비총액: 절삭(인건비합),
      인건비절삭액: 인건비합 - 절삭(인건비합),
    };
  }

  return { lineAmount: lineAmount, lineWage: lineWage, calcQuote: calcQuote, 절삭: 절삭, 절삭단위: 절삭단위,
           금액포맷: 금액포맷, 금액파싱: 금액파싱, 금액나누기: 금액나누기, 금액조정: 금액조정,
           조정계산: 조정계산, 총액조정: 총액조정 };
});
