// 눈으로 확인해 통과한 쪽만 골라, 색판 중심을 "사진 크기에 무관한 비율"로 저장한다.
const fs = require('fs');
const { 칸중심들 } = require('./격자');
const 쪽목록 = require('./쪽목록');

// 격자모음.jpg 를 눈으로 보고 점이 색판 안에 정확히 들어간 쪽만 통과시켰다.
const 확인됨 = ['p107', 'p18', 'p19', 'p23', 'p72', 'p75', 'p77', 'p78'];
const 설정표 = {
  'p14': { 어두움: 25, 채도: 6, 침식: 2 }, 'p15': { 어두움: 25, 채도: 6, 침식: 4 },
  'p23': { 어두움: 25, 채도: 6, 침식: 7 }, 'p72': { 어두움: 18, 채도: 18, 침식: 5 },
  'p75': { 어두움: 18, 채도: 18, 침식: 5 }, 'p77': { 어두움: 18, 채도: 18, 침식: 5 },
  'p78': { 어두움: 18, 채도: 18, 침식: 5 }, 'p101': { 어두움: 4, 채도: 8, 침식: 3 },
  'p107': { 어두움: 13, 채도: 13, 침식: 5 }, 'p17': { 어두움: 8, 채도: 6, 침식: 7 },
  'p18': { 어두움: 4, 채도: 16, 침식: 7 }, 'p19': { 어두움: 9, 채도: 10, 침식: 5 },
  'p20': { 어두움: 9, 채도: 10, 침식: 5 },
};

(async () => {
  const 나온것 = [];
  for (const 쪽 of 쪽목록) {
    const 이름 = 쪽.쪽.split(' ')[0];
    if (!확인됨.includes(이름)) continue;
    const g = await 칸중심들(쪽, 설정표[이름]);
    if (g.오류) { console.log(이름, '✗', g.오류); continue; }
    나온것.push({
      파일: 쪽.파일, 쪽: 쪽.쪽,
      점: g.중심.map((c, i) => ({ 코드: 쪽.코드[i], x: +(c.cx / g.r.o.폭).toFixed(5), y: +(c.cy / g.r.o.높이).toFixed(5) })),
    });
    console.log(이름.padEnd(6), g.중심.length, '점');
  }
  fs.writeFileSync('검증/점.json', JSON.stringify(나온것, null, 1), 'utf8');
  console.log('\n합계', 나온것.reduce((a, p) => a + p.점.length, 0), '건 →', '검증/점.json');
})();
