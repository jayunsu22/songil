// 우드 사진의 상위 10위에 솔리드가 몇 개 끼는가. 사장님이 겪은 '어이없는 상황' 을 숫자로.
const { 재기 } = require('./측정');
const 배포 = { 보정: '흰점', 기준: 245, 검은점빼기: true, 검은점분위: 0.005, 한계: 2.5, 무채색문턱: 0.18, 세기: 0.6, 상한: 12, 개수: 30, 넓은원: false };
(async () => {
  for (const [이름, o] of [['예전', { 세톤: false, 대표톤비중: 1, 무늬어긋남벌점: 0 }], ['새 설정', { 대표톤비중: 0.7, 무늬어긋남벌점: 8 }]]) {
    const 기 = (await 재기(Object.assign({}, 배포, o))).filter(r => r.제품 && r.상위카테고리);
    const 우 = 기.filter(r => r.제품.카테고리 === '우드');
    const 솔 = 기.filter(r => r.제품.카테고리 === '솔리드');
    const 셈 = (목, k) => 목.reduce((a, r) => a + r.상위카테고리.filter(c => c === k).length, 0);
    const 총 = (목) => 목.reduce((a, r) => a + r.상위카테고리.length, 0);
    console.log(이름.padEnd(6),
      '우드 사진 상위10 중 솔리드 ' + (셈(우, '솔리드') / 총(우) * 100).toFixed(0) + '%, 우드 ' + (셈(우, '우드') / 총(우) * 100).toFixed(0) + '%',
      '| 솔리드 사진 상위10 중 우드 ' + (셈(솔, '우드') / 총(솔) * 100).toFixed(0) + '%, 솔리드 ' + (셈(솔, '솔리드') / 총(솔) * 100).toFixed(0) + '%');
  }
})();
