// 견적요청 v2 금액 계산. DOM/네트워크에 손대지 않는 순수 모듈.
//
// 품목은 필름현장관리자 품목설정(방2문+틀, 거실샤시1 …)에서 고르고, 금액은 에어테이블
// '시공품목정보'(1분견적·방문견적이 쓰는 표)의 식을 그대로 쓴다:
//     줄 금액 = 필름 m × (인건비단가 + 필름단가) × 난이도
// 자재비단가(9,000) 자리에는 그 줄에서 고른 필름의 단가가 들어간다.
//
// 관리자 품목 → 표 줄 연결은 이름 규칙이다. 시공범위(문틀만·문짝만)와 샤시 종류(2중창 등)에 따라
// 표의 다른 줄을 쓴다 - 문틀만 시공을 방문 단가로 치면 112,000원짜리가 68,000원이 된다.
// 표에 맞는 줄이 없는 품목(프레임·파티션 …)은 null → 화면에서 단가를 정하면(고정) 그걸 쓴다.
// node 테스트: test/request_price.test.js
(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.RequestPrice = factory();
})(typeof self !== 'undefined' ? self : this, function () {
  'use strict';

  const 시공범위들 = ['문+틀 양쪽면 시공', '문+틀 한쪽면 시공', '문틀만 시공', '문짝만 시공', '문짝 앞면만 시공', '문짝 뒷면만 시공', '문선만 시공'];
  const 샤시종류들 = ['2중창', '단창', '시스템', '상가 양쪽', '상가 한쪽'];
  const 샤시표 = { '2중창': '샤시(2중창)', 단창: '샤시(단창)', 시스템: '시스템샤시', '상가 양쪽': '상가샤시(양쪽시공)', '상가 한쪽': '상가샤시(한쪽시공)' };
  const 난이도들 = [1.0, 1.1, 1.2, 1.3, 1.5];
  const 기본필름단가 = 9000;

  /* 길이(m) 품목의 보통 길이. 2026-10-17 발행 견적 68건의 수량 중앙값(표본 5건 이상만),
     아치는 사장님이 정한 기본 5m. 없는 품목은 길이를 골라야 금액이 나온다. */
  const 보통길이 = {
    '샤시(2중창)': 3, '샤시(단창)': 3, 시스템샤시: 3, '상가샤시(양쪽시공)': 3, '상가샤시(한쪽시공)': 3,
    수납장: 3, 냉장고장: 2, 싱크대: 8, '싱크대 하부장': 7, '싱크대 상부장': 4, 등박스: 12, 가벽: 10, 아치: 5,
  };

  const 붙임 = (s) => String(s || '').replace(/\s+/g, '');
  const m1 = (v) => Math.round(v * 10) / 10;
  const 수 = (v) => { const n = Number(v); return v === '' || v == null || isNaN(n) ? null : n; };

  const is샤시 = (p) => 붙임(p && p.품목명).indexOf('샤시') >= 0 && !/기둥/.test(붙임(p && p.품목명));

  /* 관리자 품목 → 표 줄 이름 (시공범위·샤시종류 반영). 못 찾으면 null.
     순서가 중요하다: '신발장문짝'·'수납장' 같은 가구를 문보다 먼저, 중문을 방문보다 먼저 본다. */
  function 표줄이름(품목, 설정) {
    const n = 붙임(품목 && 품목.품목명);
    const s = 설정 || {};
    if (!n || /^2층/.test(n)) return null;                       // 2층 품목은 그때그때
    if (/프레임/.test(n) && !/침대/.test(n)) return null;          // 프레임·거울프레임
    if (/파티션|계단|사무실|tv박스|기둥/i.test(n)) return null;
    if (is샤시(품목)) return 샤시표[s.샤시종류] || 샤시표['2중창'];
    if (/크라운/.test(n)) return '크라운몰딩';
    if (/걸레받이/.test(n)) return '걸레받이';
    if (/몰딩/.test(n)) return '몰딩';
    if (/하부장/.test(n)) return '싱크대 하부장';
    if (/상부장/.test(n)) return '싱크대 상부장';
    if (/싱크대/.test(n)) return '싱크대';
    if (/신발장/.test(n)) return '신발장';
    if (/냉장고장/.test(n)) return '냉장고장';
    if (/붙박이/.test(n)) return '붙박이장';
    if (/수납장/.test(n)) return '수납장';
    if (/화장대/.test(n)) return '화장대';
    if (/침대/.test(n)) return '침대 프레임';
    if (/중간알판/.test(n)) return '중간알판';
    if (/알판/.test(n)) return '알판';
    if (/웨인스코팅/.test(n)) return '웨인스코팅';
    if (/등박스/.test(n)) return '등박스';
    if (/아트월/.test(n)) return '아트월';
    if (/가벽/.test(n)) return '가벽';
    if (/아치/.test(n)) return '아치';
    // 여기부터 문. 시공범위가 문틀만·문짝만이면 표의 틀·문짝 줄로 바꾼다
    let 문 = null;
    if (/중문/.test(n)) 문 = '중문';
    else if (/방화문/.test(n)) 문 = '방화문';
    else if (/현관문/.test(n)) 문 = '현관문';
    else if (/터닝도어|^(거실|주방)베란다문$/.test(n)) 문 = '터닝도어';
    else if (/실외기실문|베란다문/.test(n)) 문 = '실외기실문';
    else if (/세탁실문/.test(n)) 문 = '세탁실문';
    else if (/화장실문/.test(n)) 문 = '화장실문';
    else if (/문/.test(n)) 문 = '방문';
    if (!문) return null;
    if (s.시공범위 === '문틀만 시공') return 문 === '중문' ? '중문틀' : '문틀';
    if (s.시공범위 === '문짝만 시공') return 문 === '중문' ? '중문짝' : '문짝';
    return 문;
  }

  // 문 줄인가 (시공범위를 고르는 줄)
  function is문(품목) {
    const 이름 = 표줄이름(품목, {});
    return ['방문', '화장실문', '세탁실문', '실외기실문', '방화문', '현관문', '터닝도어', '중문'].indexOf(이름) >= 0;
  }

  /* 계산 기준. 고정(사장님이 정한 단가)이 있으면 그것이 먼저다.
     { 표이름, 인건비단가, 단위: 'm'(길이를 고름) | '개'(필름 m 를 고름), 소모율, 기본길이, 기본m } */
  function 기준(품목, 설정, 표, 고정) {
    const 정한 = 고정 && 품목 && 고정[품목.품목명];
    if (정한 && 수(정한.인건비단가) != null) {
      return { 표이름: 품목.품목명, 인건비단가: 수(정한.인건비단가), 단위: '개', 소모율: 1, 기본길이: null, 기본m: 수(정한.m) };
    }
    const 이름 = 표줄이름(품목, 설정);
    if (!이름) return null;
    const 줄 = (표 || []).find((r) => r.시공_품목명 === 이름);
    if (!줄) return null;
    const 소모 = 수(줄.자재소모량) || 0;
    if (줄.견적단위 === 'm') {
      let 길이 = 보통길이[이름] != null ? 보통길이[이름] : null;
      if (이름 === '신발장') 길이 = /2$/.test(붙임(품목.품목명)) ? 3 : 5;   // 신발장1 5m · 신발장2 3m
      return { 표이름: 이름, 인건비단가: 수(줄.인건비단가) || 0, 단위: 'm', 소모율: 소모, 기본길이: 길이, 기본m: null };
    }
    // 세트·개: 표의 소모량이 1개 기본 m. 한쪽만 하는 시공범위는 절반, 문선만은 직접 고른다
    let 기본m = 소모;
    const 범위 = (설정 || {}).시공범위;
    if (/한쪽면|앞면만|뒷면만/.test(범위 || '')) 기본m = m1(소모 / 2);
    if (범위 === '문선만 시공') 기본m = null;
    return { 표이름: 이름, 인건비단가: 수(줄.인건비단가) || 0, 단위: '개', 소모율: 1, 기본길이: null, 기본m: 기본m };
  }

  /* 한 줄 금액. 설정 = { 시공범위, 샤시종류, 길이, m, 난이도 } */
  function 줄계산(품목, 설정, 표, 고정, 필름단가) {
    const s = 설정 || {};
    const k = 기준(품목, s, 표, 고정);
    const 빈 = (문제) => ({ 기준: k, 길이: null, 필름m: 0, 인건비: 0, 자재비: 0, 합: 0, 문제: 문제 });
    if (!k) return 빈('단가없음');
    let 길이 = null, 필름m;
    if (k.단위 === 'm') {
      길이 = 수(s.길이) != null ? 수(s.길이) : k.기본길이;
      if (길이 == null) return Object.assign(빈('길이없음'), { 길이: null });
      필름m = m1(길이 * k.소모율);
    } else {
      필름m = 수(s.m) != null ? 수(s.m) : k.기본m;
      if (필름m == null) return 빈('m없음');
    }
    const 난이도 = 수(s.난이도) || 1;
    const 필름 = 수(필름단가) != null ? 수(필름단가) : 기본필름단가;
    const 합 = Math.round((k.인건비단가 + 필름) * 필름m * 난이도);
    const 인건비 = Math.round(k.인건비단가 * 필름m * 난이도);
    return { 기준: k, 길이: 길이, 필름m: 필름m, 인건비: 인건비, 자재비: 합 - 인건비, 합: 합, 문제: null };
  }

  /* 시공사진 찾기 낱말: 관리자 작업 품목명에서 구역을 떼고 끝 숫자를 뗀다 ('방2문+틀' → '문+틀') */
  function 찾을낱말(품목명) {
    return String(품목명 || '')
      .replace(/^\s*\d+층\s*/, '')
      .replace(/^\s*(방\d+|거실|주방|현관)\s*/, '')
      .replace(/\s*\d+\s*$/, '')
      .trim();
  }

  /* 줄 결과들([{필름ID, 필름m, 자재비}]) → 필름별 [{필름ID, m, 금액}] (처음 나온 순서) */
  function 필름별합계(줄들) {
    const 순서 = [];
    const 합 = {};
    (줄들 || []).forEach((r) => {
      if (!r || !r.필름ID || !r.필름m) return;
      if (!합[r.필름ID]) { 합[r.필름ID] = { 필름ID: r.필름ID, m: 0, 금액: 0 }; 순서.push(r.필름ID); }
      합[r.필름ID].m = m1(합[r.필름ID].m + r.필름m);
      합[r.필름ID].금액 += r.자재비 || 0;
    });
    return 순서.map((id) => 합[id]);
  }

  return {
    시공범위들: 시공범위들, 샤시종류들: 샤시종류들, 난이도들: 난이도들, 기본필름단가: 기본필름단가,
    표줄이름: 표줄이름, 기준: 기준, 줄계산: 줄계산, is문: is문, is샤시: is샤시, 찾을낱말: 찾을낱말, 필름별합계: 필름별합계,
  };
});
