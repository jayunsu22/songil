// 필름 매칭. 어떤 제품을 어떤 순서로 보여줄지 결정한다.
//
// film_color.js 가 "두 색이 얼마나 다른가"를 답한다면, 여기는 "그래서 뭘 보여줄까"를 답한다.
// 화면 코드와 분리해 둔 이유는 순위 규칙이 이 서비스에서 가장 자주 바뀔 부분이기 때문이다.
// 실사진 테스트셋으로 가중치를 조정할 때 여기만 고치면 된다.
(function (root, factory) {
  if (typeof module === 'object' && module.exports) {
    module.exports = factory(require('./film_color.js'));
  } else {
    root.FilmMatch = factory(root.FilmColor);
  }
})(typeof self !== 'undefined' ? self : this, function (FilmColor) {

  const { deltaE2000 } = FilmColor;

  // 현장 사진은 노출과 그림자로 명도가 크게 흔들리므로 명도 비중을 절반으로 낮춘다.
  //
  // 2026-09-06 정정: "색상(a*,b*)은 자동 화이트밸런스 덕에 안정적" 이라는 전제는 틀렸다.
  // 실사진 87건을 재보니 오히려 b* 가 94% 에서 같은 방향으로 -7.75 치우쳐 있었다.
  // 자동 화이트밸런스가 안정시키는 게 아니라 자동 화이트밸런스가 원인이었다.
  // kL 로는 그 축을 손댈 수 없어서, 지금은 film_color.js 의 조명 보정으로 되돌린다.
  const 기본kL = 2;

  // 대비폭(무늬 세기) 차이에 매기는 벌점.
  // 2026-09-06 실사진 87건으로 재봤다. 0.15 든 0 이든 상위5위 적중률 차이가 1%p 안쪽이다.
  // 여기는 병목이 아니었다. 시작값을 그대로 둔다.
  const 기본대비가중치 = 0.15;

  // 색 거리 상한. 이보다 멀면 후보에서 아예 뺀다.
  //
  // 오래 5 였는데, 그 값은 '깨끗한 색끼리 비교' 를 전제로 정한 것이었다.
  // 실사진 87건을 재보니 사진색과 제품색의 ΔE 중앙값이 8.41 이었고,
  // 87건 중 74건이 상한 5 에 걸려 정답이 순위에 오르기도 전에 잘려나갔다.
  // 상한 5 → 12 로 올리면 상위5위 적중률이 14.9% → 18.4%, 30위내는 18.4% → 40.2% 가 된다.
  // 12 를 넘겨봐야 결과는 같다(개수 제한에 먼저 걸린다).
  //
  // 대신 상한이 느슨해진 만큼 화면에서 말을 바꿔야 한다. ΔE 12 짜리를 "이 중에 있습니다"
  // 라고 하면 거짓말이 된다. film_app.js 의 결과 머리글이 가장 가까운 ΔE 를 보고 문구를 고른다.
  const 기본상한 = 12;

  const 기본개수 = 10;

  /* ---------- 등급 ---------- */

  // 숫자를 그대로 보여주지 않는다. 'ΔE 2.4' 는 시공기사에게 아무 의미가 없다.
  //
  // 주의: '거의 동일' 은 색이 거의 같다는 뜻이지 같은 제품이라는 뜻이 아니다.
  // 측정 결과 전체의 65.3% 가 ΔE<1 쌍둥이를 갖는다. 화면 문구도 그렇게 써야 한다.
  function 등급(ΔE) {
    if (ΔE < 1) return '거의 동일';
    if (ΔE < 2) return '매우 유사';
    if (ΔE <= 5) return '유사';
    return null;
  }

  /* ---------- 필터 ---------- */

  // 필터는 {필드: [허용값...]} 형태. 빈 배열이나 없는 키는 '전체 허용'으로 본다.
  // 브랜드 목록을 코드에 박아두지 않는 이유: 한솔이 6번째로 들어왔고 계속 늘어난다.
  function 통과(제품, 필터) {
    if (!필터) return true;
    for (const 키 of Object.keys(필터)) {
      const 허용 = 필터[키];
      if (!허용 || !허용.length) continue;
      if (허용.indexOf(제품[키]) < 0) return false;
    }
    return true;
  }

  /* ---------- 점수 ---------- */

  // 색 거리. 이것이 후보에 들지 말지를 가르는 기준이다.
  function 색거리(질의, 제품, kL) {
    return deltaE2000(질의.lab, 제품.lab, { kL: kL });
  }

  // 최종 정렬 점수 = 색 거리 + 무늬 벌점.
  //
  // 무늬 벌점을 쓰는 이유: 평균색이 같아도 무늬가 전혀 다른 제품이 많다.
  // 측정 결과 ΔE<2 경쟁쌍의 40.3% 가 서로 다른 카테고리였다
  // (예: 솔리드 #0A0A0A 와 스톤마블 #0A0A0A 가 ΔE 0.00).
  // 나뭇결을 찍었으면 무늬 있는 제품이, 민무늬 벽을 찍었으면 솔리드가 위로 와야 한다.
  //
  // 양쪽 다 대비폭을 알 때만 적용한다. 사용자가 색을 직접 고른 경우(사진 없음)에는
  // 대비폭이 없으므로 벌점 없이 색 거리만으로 정렬한다.
  function 점수(질의, 제품, 옵션) {
    const kL = 옵션.kL, 가중치 = 옵션.대비가중치;
    const ΔE = 색거리(질의, 제품, kL);
    let 벌점 = 0;
    if (Number.isFinite(질의.대비폭) && Number.isFinite(제품.대비폭)) {
      벌점 = 가중치 * Math.abs(질의.대비폭 - 제품.대비폭);
    }
    return { ΔE: ΔE, 점수: ΔE + 벌점, 벌점: 벌점 };
  }

  /* ---------- 검색 ---------- */

  function 옵션정리(o) {
    o = o || {};
    return {
      개수:       o.개수       != null ? o.개수       : 기본개수,
      kL:         o.kL         != null ? o.kL         : 기본kL,
      대비가중치: o.대비가중치 != null ? o.대비가중치 : 기본대비가중치,
      상한:       o.상한       != null ? o.상한       : 기본상한,
      제외id:     o.제외id     || null,
    };
  }

  // 질의: { lab, 대비폭? }
  // 반환: [{ 제품, ΔE, 점수, 등급 }] — 점수 오름차순, 최대 개수만큼
  //
  // 상한은 '점수'가 아니라 '색 거리(ΔE)'에 건다. 색은 잘 맞는데 무늬만 다른 제품을
  // 후보에서 아예 빼버리면 안 되기 때문이다. 그건 순위를 내릴 일이지 탈락시킬 일이 아니다.
  function 검색(제품목록, 질의, 필터, 옵션) {
    const o = 옵션정리(옵션);
    if (!질의 || !질의.lab) return [];

    const 후보 = [];
    for (const p of 제품목록) {
      if (o.제외id && p.id === o.제외id) continue;
      if (!통과(p, 필터)) continue;
      const s = 점수(질의, p, o);
      if (s.ΔE > o.상한) continue;
      후보.push({ 제품: p, ΔE: s.ΔE, 점수: s.점수, 등급: 등급(s.ΔE) });
    }

    후보.sort(function (a, b) {
      if (a.점수 !== b.점수) return a.점수 - b.점수;
      return a.ΔE - b.ΔE; // 동점이면 색이 더 가까운 쪽
    });
    return 후보.slice(0, o.개수);
  }

  // "이 제품 재고가 없다. 다른 브랜드에서 제일 비슷한 것" — 자재상·시공기사의 실제 질문.
  // 측정 결과 86.7% 의 제품이 타 브랜드에 ΔE 2 이내 대체품을 갖는다.
  // 사진 매칭보다 성공률이 높은 기능이다.
  function 타브랜드대체품(제품목록, 기준제품, 옵션) {
    const 대상 = 제품목록.filter(function (p) { return p.제조사 !== 기준제품.제조사; });
    return 검색(
      대상,
      { lab: 기준제품.lab, 대비폭: 기준제품.대비폭 },
      null,
      Object.assign({ 제외id: 기준제품.id }, 옵션)
    );
  }

  /* ---------- 훑어보기 분류 ---------- */

  // 사람은 필름을 색상환에서 고르지 않는다. "밝은 오크냐 짙은 월넛이냐"로 고른다.
  //
  // 한 제품이 여러 분류에 나와도 된다. 필름 번호는 어차피 하나라 중복 노출은 손해가 아니고,
  // 경계에 걸친 제품을 한쪽에만 넣어서 못 찾게 되는 쪽이 실제 손해다.
  // 예: L*=88 의 아주 옅은 회색은 '화이트'로 찾는 사람도, '라이트그레이'로 찾는 사람도 봐야 한다.
  //
  // 그래서 분류는 1:1 이 아니라 1:다 이다. 아래 규칙은 전부 겹침을 전제로 만들어졌다.

  const 우드톤정의 = [
    { 이름: '아주 밝은', 설명: '화이트·아이보리' },
    { 이름: '밝은',      설명: '내추럴·오크' },
    { 이름: '중간',      설명: '티크·월넛' },
    { 이름: '짙은',      설명: '웬지·다크' },
    { 이름: '붉은',      설명: '체리·적갈' },
  ];

  // 명도 경계. 경계마다 ±겹침폭 만큼은 양쪽 모두에 넣는다.
  const 우드구간 = [
    { 이름: '짙은',      최소: -1, 최대: 45 },
    { 이름: '중간',      최소: 45, 최대: 62 },
    { 이름: '밝은',      최소: 62, 최대: 74 },
    { 이름: '아주 밝은', 최소: 74, 최대: 999 },
  ];
  // 겹침폭 5 = 경계 위아래 5씩은 양쪽 모두에 넣는다.
  // 넉넉하게 잡은 값이다. 한 제품이 여러 분류에 나오는 건 손해가 아니지만
  // 경계에 걸린 제품을 못 찾는 건 손해라서, 애매하면 넣는 쪽으로 기운다.
  const 겹침폭 = 5;

  // 체리(붉은기)는 밝기와 축이 달라서 별도로 '덧붙인다'. 빼내지 않는다.
  // 중간 밝기 체리는 '중간'에도 '붉은'에도 나와야 맞다.
  //
  // 문턱 a*>=8.5 는 검증한 값이다: 제품명에 Cherry/체리가 든 11건을 전부 잡는다.
  // 예전에는 12 를 썼는데 '연체리'(a*=9.9, 8.6) 두 건을 놓쳤다. 겹침을 허용하면서
  // 후하게 잡아도 손해가 없어졌다 — 잡힌 제품은 자기 밝기 분류에도 그대로 남기 때문이다.
  const 체리a = 8.5;

  function 우드톤들(제품) {
    if (!제품 || 제품.카테고리 !== '우드' || !제품.lab) return [];
    const L = 제품.lab.L;
    const out = 우드구간
      .filter(function (g) { return L >= g.최소 - 겹침폭 && L < g.최대 + 겹침폭; })
      .map(function (g) { return g.이름; });
    if (제품.lab.a >= 체리a) out.push('붉은');
    return out;
  }

  function 채도(lab) { return Math.sqrt(lab.a * lab.a + lab.b * lab.b); }

  // 일반색은 저장된 '색상계열'을 항상 유지하고, 색 자체가 다른 그룹의 영역에
  // 들어오면 거기에도 넣는다. 저장값을 덮어쓰지 않는 이유는 그것이 사람이 정한
  // 분류이고 대체로 맞기 때문이다. 우리는 '경계에서 빠뜨린 것'만 보탠다.
  //
  // 무채색 사다리는 범위를 겹치게 잡았다(84~89, 60~65, 24~29 구간이 양쪽 소속).
  // 실측한 저장 분류의 경계가 대략 L* 86 / 62 / 26 이었다.
  // 화이트만 예외로 엄격하게 잡는다. 업체가 가장 많이 고르는 분류인데 느슨하면
  // 베이지·연회색이 잔뜩 섞여 정작 흰색을 고르기 어려워진다(느슨할 때 322건이었고
  // 그중엔 #D9D1BE 채도 10.4 같은 완전 베이지도 있었다).
  //
  // 두 갈래로 잡는다.
  //  1) 색이 진짜 흰 것: L*>=92 이고 채도<=5
  //  2) 이름이 화이트인 것: 제조사가 '화이트/백색/중백/유백/밀키' 라고 부르면 그 판단을 존중한다.
  //     단 어느 정도는 밝아야 한다(L*>=85). '매트 코타화이트'(L*=76) 같은 건 흰색이 아니다.
  // '아이보리'는 뺐다 — 베이지 쪽에 가깝고, 넣으면 화이트가 다시 탁해진다.
  const 화이트낱말 = ['화이트', 'white', '백색', '중백', '유백', '밀키', 'milky'];
  function 이름이화이트(p) {
    const t = ((p.색상명 || '') + ' ' + (p.코드 || '')).toLowerCase();
    return 화이트낱말.some(function (w) { return t.indexOf(w) >= 0; });
  }

  // 핑크와 퍼플은 각각 8건, 3건뿐이라 따로 두면 버튼만 차지하고 고를 것이 없다.
  // 하나로 묶는다. 데이터를 고치지 않고 표시 단계에서만 합친다 -- 원본 색상계열은 살아 있다.
  const 계열합침 = { '핑크': '핑크·퍼플', '퍼플': '핑크·퍼플' };

  const 검정낱말 = ['블랙', 'black', '흑색', '먹색'];
  function 이름이검정(p) {
    const t = ((p.색상명 || '') + ' ' + (p.코드 || '')).toLowerCase();
    return 검정낱말.some(function (w) { return t.indexOf(w) >= 0; });
  }

  const 색영역 = [
    { 이름: '화이트', 맞나: function (p) {
        if (p.lab.L >= 92 && 채도(p.lab) <= 5) return true;
        return 이름이화이트(p) && p.lab.L >= 85;
      } },
    { 이름: '라이트그레이', 맞나: function (p) { return p.lab.L >= 58 && p.lab.L < 91 && 채도(p.lab) <= 12; } },
    { 이름: '그레이',       맞나: function (p) { return p.lab.L >= 22 && p.lab.L < 67 && 채도(p.lab) <= 12; } },
    // 블랙도 화이트와 같은 이유로 엄격하게 잡는다. 느슨할 때 131건이었는데
    // 그 안에 'Bronze Gold'(L*=30.7), 'French Navy', '브라운' 까지 들어 있었다.
    //  1) 색이 진짜 검은 것: L*<=20 이고 채도<=8
    //  2) 이름이 검정인 것: 블랙/black/흑색/먹색. 단 L*<=30 이어야 한다
    //     ('블랙펄' L*=64 처럼 이름만 블랙인 것이 있다).
    // '차콜/charcoal' 은 낱말에서 뺐다 — 한글 '차콜' 제품은 L* 30~37 의 진회색이라
    // 검정이 아니다. 영문 charcoal(L*=18)은 어차피 색 기준으로 걸린다.
    { 이름: '블랙', 맞나: function (p) {
        if (p.lab.L <= 20 && 채도(p.lab) <= 8) return true;
        return 이름이검정(p) && p.lab.L <= 30;
      } },
    // 베이지는 따뜻한 쪽만. a*>0 조건을 빼면 세이지 그린 같은 것이 베이지로 들어온다.
    // 넉넉하게 잡되 이 조건만은 유지한다 — 초록을 베이지에 넣는 건 겹침이 아니라 오분류다.
    { 이름: '베이지',       맞나: function (p) {
        const c = 채도(p.lab);
        return p.lab.L >= 52 && c >= 3 && c <= 20 && p.lab.b > 4 && p.lab.a > 0;
      } },
  ];

  /* ---------- 재질 ----------

     색과는 다른 축이다. '화이트' 안에 매끈한 솔리드와 돌 무늬가 섞여 있어서
     고를 때 헷갈린다는 말이 나왔다. 색은 색대로, 재질은 재질대로 볼 수 있어야 한다.

     우드는 여기 넣지 않는다. 우드는 컬러별 보기의 밝기 5단계가 이미 잘 갈라주고,
     958건이라 재질 탭에 넣으면 나머지가 다 묻힌다.

     에어테이블의 카테고리를 그대로 쓴다. 화면에 보일 이름만 손본다 —
     스톤과 마블은 데이터에서 갈라져 있지 않다(세부분류가 '마블'인 것은 8건뿐이고
     97건이 '스톤마블'로 뭉뚱그려져 있다). 없는 구분을 지어내지 않는다. */
  const 재질순서 = ['솔리드', '스톤·마블', '메탈', '패브릭', '내추럴서피스', '레더', '하이글로시', '기타'];
  const 재질이름 = { '스톤마블': '스톤·마블' };
  const 재질설명 = {
    '솔리드': '무늬 없는 단색',
    '스톤·마블': '돌·대리석 무늬',
    '메탈': '금속 질감',
    '패브릭': '직물·텍스타일',
    '내추럴서피스': '천연 소재 질감',
    '레더': '가죽 무늬',
    '하이글로시': '거울처럼 광택',
    '기타': '그 밖의 것',
  };

  function 재질이름찾기(제품) {
    if (!제품 || !제품.카테고리 || 제품.카테고리 === '우드') return null;
    return 재질이름[제품.카테고리] || 제품.카테고리;
  }

  // 한 제품이 속하는 모든 분류. [{군, 이름}, ...]
  function 분류들(제품) {
    if (!제품) return [];
    const 톤 = 우드톤들(제품);
    if (톤.length) return 톤.map(function (t) { return { 군: '우드', 이름: t }; });

    const 이름들 = new Set();

    // 저장된 색상계열은 사람이 정한 값이라 그대로 살린다.
    // 다만 '화이트'만은 예외다 — 저장값으로 무조건 통과시키면 위 엄격한 기준이 무력해진다.
    // (저장 색상계열이 화이트인 250건은 L* 85~100 으로 폭이 넓다)
    // 화이트와 블랙은 예외다. 저장값으로 무조건 통과시키면 위 엄격한 기준이 무력해진다.
    // 둘 다 업체가 자주 고르는 분류라, 넓으면 분류가 있으나 마나가 된다.
    if (제품.색상계열 && 제품.색상계열 !== '화이트' && 제품.색상계열 !== '블랙') {
      이름들.add(계열합침[제품.색상계열] || 제품.색상계열);
    }

    if (제품.lab) {
      색영역.forEach(function (r) { if (r.맞나(제품)) 이름들.add(r.이름); });
    }

    // 안전망: 어떤 규칙에도 안 걸리면 사람이 정한 원래 값으로 되돌린다.
    // 임계값을 아슬아슬하게 못 넘긴 제품(예: L*=96 채도 5.6 의 아주 옅은 흰색)이
    // 어디에도 안 나와 사라지는 일을 막는다. 안 보이는 게 제일 나쁘다.
    if (!이름들.size) 이름들.add(계열합침[제품.색상계열] || 제품.색상계열 || '기타');

    const 나온것 = [...이름들].map(function (n) { return { 군: '일반색', 이름: n }; });
    const 재 = 재질이름찾기(제품);
    if (재) 나온것.push({ 군: '재질', 이름: 재 });
    return 나온것;
  }

  function 속하나(제품, 군, 이름) {
    return 분류들(제품).some(function (c) { return c.군 === 군 && c.이름 === 이름; });
  }

  // 훑어보기 버튼 목록. 건수도 같이 준다 — 퍼플 3건 같은 것을 숨기면 "왜 없지" 하게 된다.
  // 겹침 때문에 건수 합계는 전체보다 크다. 그게 정상이다.
  function 분류목록(제품목록, 군) {
    const m = new Map();
    제품목록.forEach(function (p) {
      분류들(p).forEach(function (c) {
        if (c.군 === 군) m.set(c.이름, (m.get(c.이름) || 0) + 1);
      });
    });
    if (군 === '재질') {
      // 건수 순이 아니라 정해둔 순서로 둔다. 우드·일반색과 같은 이유 —
      // 목록이 데이터에 따라 들썩이면 매번 눈으로 다시 찾아야 한다.
      return 재질순서
        .filter(function (n) { return m.has(n); })
        .map(function (n) { return { 값: n, 설명: 재질설명[n] || null, 건수: m.get(n) }; });
    }
    if (군 === '우드') {
      return 우드톤정의
        .filter(function (d) { return m.has(d.이름); })
        .map(function (d) { return { 값: d.이름, 설명: d.설명, 건수: m.get(d.이름) }; });
    }
    // 일반색도 건수 순이 아니라 색 순서로 고정한다. 우드를 밝기 순으로 둔 것과 같은 이유다.
    // 특히 화이트는 업체가 가장 많이 고르는 분류인데, 건수 순으로 두면 4번째로 밀린다.
    // 무채색 사다리(밝은->어두운) -> 따뜻한 중성 -> 유채색 순으로 늘어놓는다.
    const 색순서 = ['화이트', '라이트그레이', '그레이', '블랙', '베이지', '브라운'];
    // (핑크·퍼플은 유채색이라 뒤쪽 건수 순에 들어간다)
    const 있는것 = [...m.entries()];
    const 앞 = 색순서
      .filter(function (n) { return m.has(n); })
      .map(function (n) { return { 값: n, 설명: null, 건수: m.get(n) }; });
    const 뒤 = 있는것
      .filter(function (e) { return 색순서.indexOf(e[0]) < 0; })
      .sort(function (a, b) { return b[1] - a[1]; })
      .map(function (e) { return { 값: e[0], 설명: null, 건수: e[1] }; });
    return 앞.concat(뒤);
  }

  // 훑어보기 정렬. '그 분류다운 것'이 앞에 오게 한다.
  //
  // 대부분은 옅은 것 -> 짙은 것 순이 자연스럽다. 눈이 그라데이션을 따라간다.
  // 그런데 블랙만은 반대다 — 가장 검은 것이 제일 블랙다운데 옅은순으로 두면 맨 뒤로 밀린다.
  // 밝기가 같으면 채도가 낮은(더 무채색인) 쪽을 앞에 둔다.
  function 훑어보기정렬(이름) {
    const 짙은게먼저 = (이름 === '블랙');
    return function (a, b) {
      if (a.lab.L !== b.lab.L) return 짙은게먼저 ? a.lab.L - b.lab.L : b.lab.L - a.lab.L;
      return 채도(a.lab) - 채도(b.lab);
    };
  }

  function 분류목록보기(제품목록, 군, 이름) {
    return 제품목록
      .filter(function (p) { return 속하나(p, 군, 이름); })
      .sort(훑어보기정렬(이름));
  }

  // 칩 필터 목록을 데이터에서 만든다. 브랜드가 늘어나면 칩도 저절로 늘어난다.
  // 화면 코드에 '5개 브랜드'를 박아두지 않기 위한 함수다.
  function 필터후보(제품목록, 키) {
    const m = new Map();
    제품목록.forEach(function (p) {
      const v = p[키];
      if (v == null || v === '') return;
      m.set(v, (m.get(v) || 0) + 1);
    });
    return [...m.entries()]
      .sort(function (a, b) { return b[1] - a[1]; })
      .map(function (e) { return { 값: e[0], 건수: e[1] }; });
  }

  return {
    등급: 등급,
    통과: 통과,
    색거리: 색거리,
    점수: 점수,
    검색: 검색,
    타브랜드대체품: 타브랜드대체품,
    필터후보: 필터후보,
    우드톤들: 우드톤들,
    분류들: 분류들,
    속하나: 속하나,
    분류목록: 분류목록,
    분류목록보기: 분류목록보기,
    훑어보기정렬: 훑어보기정렬,
    기본값: {
      kL: 기본kL, 대비가중치: 기본대비가중치, 상한: 기본상한, 개수: 기본개수,
      체리a: 체리a, 겹침폭: 겹침폭,
    },
  };
});
